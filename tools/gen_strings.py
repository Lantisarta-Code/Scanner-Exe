"""Makes src/gen_strings.h from the Python program: the texts in both languages and the page scripts,
so the C++ program says and does exactly what the Python one did."""
import ast, sys
src = open(sys.argv[1], encoding="utf-8").read()
tree = ast.parse(src)
vals = {}
for n in tree.body:
    if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id in ("TR", "FILTER_JS", "CLICK_JS", "REPORT_JS"):
        vals[n.targets[0].id] = ast.literal_eval(n.value)
tr = vals["TR"]
# texts that are different in the C++ program (no Python, no Playwright, Excel is built in)
over = {
    "en": {
        "env_info": "{win} detected - the browser is driven with WebDriver",
        "err_driver_missing": "{name} was not found. Click \"Download automatically\" next to the driver path (or run:  EasyCentralBot.exe --get-driver {kind} ), or put the driver that matches your browser's version in {folder}",
        "missing_pkg": "The Excel file could not be read.",
    },
    "tr": {
        "env_info": "{win} algılandı - tarayıcı WebDriver ile yönetiliyor",
        "err_driver_missing": "{name} bulunamadı. Sürücü yolunun yanındaki \"Otomatik indir\" düğmesine tıklayın (ya da şunu çalıştırın:  EasyCentralBot.exe --get-driver {kind} ) veya tarayıcınızın sürümüne uyan sürücüyü {folder} klasörüne koyun.",
        "missing_pkg": "Excel dosyası okunamadı.",
    },
}
def c(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return '"' + s + '"'
out = ["// Generated by tools/gen_strings.py - do not edit by hand.", "#pragma once", "",
       "struct TrEntry { const char* key; const char* en; const char* tr; };", "static const TrEntry TR_TABLE[] = {"]
for k in tr["en"]:
    en = over["en"].get(k, tr["en"][k]); trk = over["tr"].get(k, tr["tr"].get(k, en))
    out.append("    {%s, u8%s, u8%s}," % (c(k), c(en), c(trk)))
out.append("};")
for name in ("FILTER_JS", "CLICK_JS", "REPORT_JS"):
    assert ")ECB\"" not in vals[name]
    out.append("static const char* const %s = u8R\"ECB(%s)ECB\";" % (name, vals[name]))
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print("texts:", len(tr["en"]))
